package juegoLaberinto;

public class Nodo {
//ATRIBUTOS ---------------------------------------------------------------------------------------------------------------------------------------------------------
	private int fila;
	private int columna;

//CONSTRUCTORES -----------------------------------------------------------------------------------------------------------------------------------------------------
	public Nodo(int fila, int columna) {
		this.fila = fila;
		this.columna = columna;
	}
	
//METODOS GENERALES -------------------------------------------------------------------------------------------------------------------------------------------------
	@Override
	public String toString() {
	    return "(" + fila + "," + columna + ")";
	}
	
//GETTERS -----------------------------------------------------------------------------------------------------------------------------------------------------------
	public int getFila() {
		return this.fila;
	}
	
	public int getColumna() {
		return this.columna;
	}
	
}
